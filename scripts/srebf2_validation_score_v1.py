#!/usr/bin/env python3
"""Pre-register then score the GSE271000 validation cohort.
Run from repository root:
  python scripts/srebf2_validation_score_v1.py --freeze-policy
  python scripts/srebf2_validation_score_v1.py --score
"""
import argparse, hashlib, json
from pathlib import Path
import numpy as np
import pandas as pd

ROOT = Path.cwd()
SIG = ROOT/'results/signature/discovery_v1'
COUNT = ROOT/'results/counts/validation/GSE271000/GSE271000_validation_gene_counts.tsv'
META = ROOT/'metadata/GSE271000_validation_samples.tsv'
OUT = ROOT/'results/signature_validation/GSE271000_v1'
POLICY = ROOT/'metadata/SREBF2_VALIDATION_SCORING_POLICY_v1.json'
SREBF2 = 'ENSG00000198911.13'

def sha(path):
    h = hashlib.sha256()
    with open(path,'rb') as f:
        for chunk in iter(lambda: f.read(1048576), b''): h.update(chunk)
    return h.hexdigest()

def freeze():
    if POLICY.exists(): raise SystemExit(f'Policy exists; refusing overwrite: {POLICY}')
    manifest = json.loads((SIG/'SIGNATURE_MANIFEST.json').read_text())
    policy = {
        'version':'validation_scoring_v1', 'status':'frozen_before_validation_scoring',
        'discovery_manifest_sha256':sha(SIG/'SIGNATURE_MANIFEST.json'),
        'positive_signature_sha256':sha(SIG/'SREBF2_SIGNATURE_POSITIVE.tsv'),
        'negative_signature_sha256':sha(SIG/'SREBF2_SIGNATURE_NEGATIVE.tsv'),
        'expected_signature_counts':{'positive':795,'negative':531},
        'sample_cohort':'GSE271000; eight HepG2 samples; 2 controls, 2 per shSREBP2 hairpin 664/665/667',
        'gene_ids':'exact versioned Ensembl IDs; no symbol or version remapping',
        'normalization':'DESeq2-style median-of-ratios using genes with positive counts in every sample; geometric mean across all eight samples; median of positive ratios per sample',
        'expression':'log2(normalized counts + 1)',
        'ranking_universe':'all 78,932 matrix genes, including zero-count genes; midrank ties within each sample; percentile=(rank-0.5)/N',
        'primary_score':'mean percentile of 795 decreased-in-KO genes minus mean percentile of 531 increased-in-KO genes; equal weight per gene and equal weight per component',
        'missing_gene_policy':'error on missing signature genes, missing SREBF2, duplicated IDs, or missing counts; no imputation',
        'primary_comparison':'descriptive control-versus-each-hairpin differences in signature score and SREBF2 log2 normalized expression; no inferential p values',
        'expected_direction':'signature score and SREBF2 expression lower in knockdown than control',
        'secondary_qc':'count of genes with nonzero counts by sample and group; signature expression coverage; per-sample normalization size factors',
        'validation_gene_selection':'none; frozen discovery genes only',
        'discovery_source_dataset':manifest['source_dataset'],
    }
    POLICY.parent.mkdir(parents=True,exist_ok=True)
    POLICY.write_text(json.dumps(policy,indent=2)+'\n')
    print('POLICY FROZEN:',POLICY,'SHA256:',sha(POLICY))
    print('Do not edit this file after examining validation scores.')

def score():
    if not POLICY.is_file(): raise SystemExit('Freeze policy first with --freeze-policy')
    if OUT.exists(): raise SystemExit(f'Refusing to overwrite validation output: {OUT}')
    p = json.loads(POLICY.read_text())
    if p['discovery_manifest_sha256'] != sha(SIG/'SIGNATURE_MANIFEST.json'): raise ValueError('Discovery manifest checksum mismatch')
    for direction in ('positive','negative'):
        if p[f'{direction}_signature_sha256'] != sha(SIG/f'SREBF2_SIGNATURE_{direction.upper()}.tsv'): raise ValueError('Signature checksum mismatch')
    positive = pd.read_csv(SIG/'SREBF2_SIGNATURE_POSITIVE.tsv',sep='\t',dtype={'gene_id':str})['gene_id'].tolist()
    negative = pd.read_csv(SIG/'SREBF2_SIGNATURE_NEGATIVE.tsv',sep='\t',dtype={'gene_id':str})['gene_id'].tolist()
    if (len(positive),len(negative)) != (795,531) or len(set(positive+negative))!=1326: raise ValueError('Unexpected signature composition')
    meta = pd.read_csv(META,sep='\t',dtype=str)
    expected = {'control':2,'shSREBP2_664':2,'shSREBP2_665':2,'shSREBP2_667':2}
    if len(meta)!=8 or meta['run'].duplicated().any() or meta.groupby('group').size().to_dict()!=expected: raise ValueError('Unexpected sample metadata')
    df = pd.read_csv(COUNT,sep='\t',dtype={'gene_id':str})
    if df.shape!=(78932,9) or df['gene_id'].duplicated().any() or df.columns.tolist()!=['gene_id']+meta['run'].tolist(): raise ValueError('Count matrix dimensions or sample order mismatch')
    x = df.set_index('gene_id')
    if x.isna().any().any() or not np.isfinite(x.to_numpy(dtype=float)).all(): raise ValueError('Missing or nonfinite counts')
    v = x.to_numpy(dtype=float)
    if np.any(v<0) or np.any(v!=np.floor(v)): raise ValueError('Counts must be nonnegative integers')
    missing = set(positive+negative+[SREBF2])-set(x.index)
    if missing: raise ValueError(f'Missing required genes: {sorted(missing)[:10]}')
    # Match DESeq2's default poscounts-excluding geometric-mean-zero approach: only genes with positive counts in every sample.
    valid = (v>0).all(axis=1)
    if not valid.any(): raise ValueError('No genes positive across all samples')
    geometric = np.exp(np.log(v[valid]).mean(axis=1))
    size = np.median(v[valid]/geometric[:,None],axis=0)
    if not np.isfinite(size).all() or (size<=0).any(): raise ValueError('Invalid size factors')
    norm = v/size[None,:]
    lognorm = np.log2(norm+1)
    # Ranking of lognorm equals ranking of raw counts within each sample, since size factors are constant per sample.
    ranks = x.rank(axis=0,method='average',ascending=True).to_numpy(dtype=float)
    percentiles = (ranks-0.5)/len(x)
    ix = pd.Index(x.index)
    pi = ix.get_indexer(positive); ni = ix.get_indexer(negative); si = ix.get_loc(SREBF2)
    pos_score = percentiles[pi,:].mean(axis=0)
    neg_score = percentiles[ni,:].mean(axis=0)
    sample = meta[['run','group','hairpin','replicate_label']].copy()
    sample['size_factor'] = size
    sample['positive_mean_percentile'] = pos_score
    sample['negative_mean_percentile'] = neg_score
    sample['signature_score'] = pos_score-neg_score
    sample['SREBF2_log2_normalized_count'] = lognorm[si,:]
    sample['positive_genes_nonzero'] = (v[pi,:]>0).sum(axis=0)
    sample['negative_genes_nonzero'] = (v[ni,:]>0).sum(axis=0)
    group = sample.groupby('group',sort=False).agg(n=('run','size'),mean_score=('signature_score','mean'),mean_SREBF2=('SREBF2_log2_normalized_count','mean')).reset_index()
    ctrl = group[group.group=='control'].iloc[0]
    group['delta_score_vs_control'] = group.mean_score-ctrl.mean_score
    group['delta_SREBF2_vs_control'] = group.mean_SREBF2-ctrl.mean_SREBF2
    OUT.mkdir(parents=True,exist_ok=False)
    sample.to_csv(OUT/'SAMPLE_SCORES.tsv',sep='\t',index=False,float_format='%.10g')
    group.to_csv(OUT/'GROUP_SUMMARY.tsv',sep='\t',index=False,float_format='%.10g')
    report={'policy_sha256':sha(POLICY),'counts_sha256':sha(COUNT),'metadata_sha256':sha(META),
            'samples':8,'matrix_genes':len(x),'genes_positive_all_samples_for_size_factors':int(valid.sum()),
            'signature_positive':len(positive),'signature_negative':len(negative),
            'all_signature_ids_matched':True,'interpretation':'descriptive exploratory external-cohort validation; no binding evidence established'}
    (OUT/'RUN_MANIFEST.json').write_text(json.dumps(report,indent=2)+'\n')
    print(group.to_string(index=False));print('Wrote:',OUT)

if __name__=='__main__':
    parser=argparse.ArgumentParser()
    g=parser.add_mutually_exclusive_group(required=True)
    g.add_argument('--freeze-policy',action='store_true');g.add_argument('--score',action='store_true')
    args=parser.parse_args()
    freeze() if args.freeze_policy else score()
